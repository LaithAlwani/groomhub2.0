/*
 * GroomHub service worker — hand-rolled (no Serwist/Workbox) because Next 16
 * runs on Turbopack by default and the Workbox webpack plugins are unreliable
 * outside webpack.
 *
 * Scope deliberately kept narrow:
 *   - `/_next/static/*`, manifest, icons:   cache-first (fingerprinted, safe forever)
 *   - Clerk JS bundle (`*.clerk.*`/npm/*): stale-while-revalidate (so the app
 *                                          shell can still hydrate during a
 *                                          brief network blip)
 *   - Navigation requests (full HTML):     network-first → /offline on failure
 *   - Everything else (Convex, Clerk API, RSC, image fetches, etc.):
 *                                          bypass entirely — go to the network
 *
 * Data caching (`useConvexCachedQuery`, TanStack persister) is intentionally
 * not part of this SW. The app no longer attempts to serve stale data offline;
 * it shows `/offline` instead. Convex live queries still work normally when
 * online.
 *
 * Bumping VERSION wipes every old cache on the next activation.
 */

const VERSION = "v5";
const DEBUG = true;
const PRECACHE_MANIFEST = "/sw-precache-manifest.json";

const CACHE_STATIC = `groomhub-static-${VERSION}`;
const CACHE_SHELL = `groomhub-shell-${VERSION}`;
const OFFLINE_URL = "/offline";

function log(...args) {
  if (DEBUG) console.log("[sw]", ...args);
}

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      // 1) Shell precache — the offline fallback page itself.
      const shellCache = await caches.open(CACHE_SHELL);
      try {
        await shellCache.add(new Request(OFFLINE_URL, { cache: "reload" }));
        log("precached", OFFLINE_URL);
      } catch (error) {
        log("precache offline-page failed", error);
      }

      // 2) Static precache — every JS / CSS / WOFF2 chunk Next produced at
      //    build time, sourced from `public/sw-precache-manifest.json`
      //    (generated by `scripts/generate-sw-manifest.mjs`). This is what
      //    makes the cached `/offline` page hydrate properly: it needs the
      //    same React + Clerk chunks the rest of the app uses.
      const staticCache = await caches.open(CACHE_STATIC);
      try {
        const response = await fetch(PRECACHE_MANIFEST, { cache: "reload" });
        if (response.ok) {
          const urls = await response.json();
          const results = await Promise.allSettled(
            urls.map((url) =>
              staticCache.add(new Request(url, { cache: "reload" })),
            ),
          );
          const ok = results.filter((r) => r.status === "fulfilled").length;
          log(`precached ${ok}/${urls.length} static chunks`);
        } else {
          log("precache manifest not found", response.status);
        }
      } catch (error) {
        log("precache manifest fetch failed", error);
      }
    })(),
  );
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(
        keys
          .filter((key) => !key.endsWith(`-${VERSION}`))
          .map((key) => {
            log("deleting old cache", key);
            return caches.delete(key);
          }),
      );
      await self.clients.claim();
      log("activated", VERSION);
    })(),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;

  const url = new URL(request.url);

  // Clerk's JS bundle lives on a per-instance subdomain
  // (e.g. big-ray-65.clerk.accounts.dev/npm/@clerk/clerk-js@6/...).
  // Cache it via stale-while-revalidate so a brief network blip doesn't
  // bring the whole app down with "Failed to load Clerk JS".
  if (isClerkStaticAsset(url)) {
    event.respondWith(staleWhileRevalidate(request, CACHE_STATIC, "clerk"));
    return;
  }

  // All other cross-origin: bypass (Convex, Clerk API, third-party).
  if (url.origin !== self.location.origin) return;

  // Cache-first for fingerprinted static assets.
  if (
    url.pathname.startsWith("/_next/static/") ||
    url.pathname.startsWith("/icons/") ||
    url.pathname === "/manifest.webmanifest" ||
    url.pathname === "/logo_new.webp" ||
    url.pathname === "/logo_wide.webp"
  ) {
    event.respondWith(cacheFirst(request, CACHE_STATIC, "static"));
    return;
  }

  // Navigation requests — try network, fall back to the precached offline
  // page when the network is gone. No per-route caching anymore; offline =
  // see the offline page.
  if (request.mode === "navigate" || request.destination === "document") {
    event.respondWith(navigationNetworkOnlyWithOfflineFallback(request));
    return;
  }
});

function isClerkStaticAsset(url) {
  const isClerkHost =
    url.hostname.endsWith(".clerk.accounts.dev") ||
    url.hostname.endsWith(".clerk.com") ||
    url.hostname.endsWith(".clerk.dev");
  if (!isClerkHost) return false;
  return (
    url.pathname.startsWith("/npm/") ||
    url.pathname.endsWith(".js") ||
    url.pathname.endsWith(".css") ||
    url.pathname.endsWith(".woff2") ||
    url.pathname.endsWith(".svg")
  );
}

async function staleWhileRevalidate(request, cacheName, kind) {
  const cache = await caches.open(cacheName);
  const cached = await cache.match(request);
  const networkPromise = fetch(request)
    .then((response) => {
      if (response.ok) {
        cache.put(request, response.clone());
        log(kind, cached ? "REVALIDATE" : "FILL", request.url);
      }
      return response;
    })
    .catch((error) => {
      if (cached) {
        log(kind, "REVALIDATE FAILED, using cache", request.url);
        return cached;
      }
      throw error;
    });
  if (cached) {
    log(kind, "HIT", request.url);
    return cached;
  }
  log(kind, "MISS → network", request.url);
  return networkPromise;
}

async function cacheFirst(request, cacheName, kind) {
  const cache = await caches.open(cacheName);
  const cached = await cache.match(request);
  if (cached) {
    log(kind, "HIT", request.url);
    return cached;
  }
  try {
    const response = await fetch(request);
    if (response.ok) {
      await cache.put(request, response.clone());
      log(kind, "FILL", request.url);
    }
    return response;
  } catch {
    return Response.error();
  }
}

async function navigationNetworkOnlyWithOfflineFallback(request) {
  try {
    return await fetch(request);
  } catch {
    log("nav OFFLINE → /offline", request.url);
    const shellCache = await caches.open(CACHE_SHELL);
    const offline = await shellCache.match(OFFLINE_URL);
    if (offline) return offline;
    return new Response(
      "<!doctype html><title>Offline</title><h1>You're offline</h1>",
      { headers: { "Content-Type": "text/html; charset=utf-8" } },
    );
  }
}
